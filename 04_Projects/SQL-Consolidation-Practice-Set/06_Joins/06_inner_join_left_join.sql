-- INNER JOIN and LEFT JOIN

-- 33. Display each order's ID, customer name, product name and quantity.
SELECT 
    o.order_id AS Order_ID,
    c.customer_name AS Customer,
    p.product_name AS Product,
    o.quantity AS Quantity
FROM
    orders o
        INNER JOIN
    products p ON o.product_id = p.product_id
        INNER JOIN
    customers c ON o.customer_id = c.customer_id;

-- 34. Display each order's ID, product name, quantity and calculated order value.
SELECT 
    o.order_id AS Order_ID,
    p.product_name AS Product,
    o.quantity AS Quantity,
    SUM(p.price * o.quantity) AS Order_Value
FROM
    orders o
        INNER JOIN
    products p ON o.product_id = p.product_id
GROUP BY order_id;

-- 35. Display all completed orders with customer names and countries.
SELECT 
    o.order_id AS Orders,
    c.customer_name AS Customer,
    c.country AS Country
FROM
    orders o
        INNER JOIN
    customers c ON o.customer_id = c.customer_id
WHERE
    o.status = 'Completed';

-- 36. List all customers and their orders, including customers who have never placed an order.
SELECT 
    c.customer_name AS Customer, o.order_id AS Orders
FROM
    customers c
        LEFT JOIN
    orders o ON c.customer_id = o.customer_id;

-- 37. Find customers who have never placed any order.
SELECT 
    c.customer_name AS Customer
FROM
    customers c
        LEFT JOIN
    orders o ON c.customer_id = o.customer_id
WHERE
    o.order_id IS NULL;

-- 38. Display each customer's name and their total completed sales revenue. Include customers with zero completed revenue.
SELECT 
    c.customer_name AS Customer,
    SUM(p.price * o.quantity) AS Completed_Sales_Revenue
FROM
    orders o
        LEFT JOIN
    customers c ON o.customer_id = c.customer_id
        LEFT JOIN
    products p ON o.product_id = p.product_id
GROUP BY Customer;

-- 39. Find the total completed revenue generated by customers in each country.
SELECT 
    c.country AS Country,
    SUM(p.price * o.quantity) AS Completed_Revenue
FROM
    orders o
        INNER JOIN
    customers c ON o.customer_id = c.customer_id
        INNER JOIN
    products p ON o.product_id = p.product_id
GROUP BY Country;
